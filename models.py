"""Database models for FoodWise (5 tables).

Tables
------
1. users          - registered accounts (Flask-Login compatible)
2. food_items     - one row per food item a user buys
3. notifications  - expiry reminders generated by the background checker
4. food_waste     - one row per reported waste event (feeds the ML model)
5. recipes        - global recipe catalogue used by the recommender
"""
from datetime import date, datetime

from flask_sqlalchemy import SQLAlchemy
from flask_login import UserMixin
from werkzeug.security import generate_password_hash, check_password_hash

from config import Config

db = SQLAlchemy()

# Shared choice lists (kept in one place so forms, templates and ML agree)
FOOD_CATEGORIES = ["Fruits", "Vegetables", "Dairy", "Meat", "Grains", "Other"]
FOOD_UNITS = ["pcs", "kg", "g", "L", "ml", "pack", "bottle"]
WASTE_REASONS = ["Expired", "Spoiled", "Over-purchased", "Not used in time", "Other"]
RECIPE_CATEGORIES = ["Breakfast", "Lunch", "Dinner", "Snack", "Dessert"]


class User(UserMixin, db.Model):
    """A registered FoodWise user."""

    __tablename__ = "users"

    id = db.Column(db.Integer, primary_key=True)
    username = db.Column(db.String(64), unique=True, nullable=False, index=True)
    email = db.Column(db.String(120), unique=True, nullable=False, index=True)
    password_hash = db.Column(db.String(256), nullable=False)
    created_at = db.Column(db.DateTime, default=datetime.utcnow)

    foods = db.relationship("FoodItem", backref="owner", lazy="dynamic",
                            cascade="all, delete-orphan")
    notifications = db.relationship("Notification", backref="user", lazy="dynamic",
                                    cascade="all, delete-orphan")
    waste_records = db.relationship("FoodWaste", backref="user", lazy="dynamic",
                                    cascade="all, delete-orphan")

    # --- password helpers (never store plain passwords) ------------------
    def set_password(self, password):
        self.password_hash = generate_password_hash(password)

    def check_password(self, password):
        return check_password_hash(self.password_hash, password)

    def __repr__(self):
        return f"<User {self.username}>"


class FoodItem(db.Model):
    """One food item the user added to their inventory."""

    __tablename__ = "food_items"

    id = db.Column(db.Integer, primary_key=True)
    user_id = db.Column(db.Integer, db.ForeignKey("users.id"), nullable=False, index=True)
    food_name = db.Column(db.String(120), nullable=False)
    category = db.Column(db.String(50), nullable=False, default="Other")
    quantity = db.Column(db.Float, nullable=False, default=1.0)
    unit = db.Column(db.String(30), nullable=False, default="pcs")
    purchase_date = db.Column(db.Date, nullable=False)
    expiry_date = db.Column(db.Date, nullable=False, index=True)
    created_at = db.Column(db.DateTime, default=datetime.utcnow)

    # --- derived status (green / orange / red) ---------------------------
    @property
    def days_to_expiry(self):
        """Positive = days left, 0 = expires today, negative = already expired."""
        return (self.expiry_date - date.today()).days

    @property
    def status(self):
        d = self.days_to_expiry
        if d < 0:
            return "expired"
        if d <= Config.REMINDER_DAYS_BEFORE:
            return "near"
        return "safe"

    STATUS_LABELS = {"safe": "Fresh", "near": "Expiring soon", "expired": "Expired"}

    def __repr__(self):
        return f"<FoodItem {self.food_name} ({self.category})>"


class Notification(db.Model):
    """An expiry reminder generated by the background scheduler."""

    __tablename__ = "notifications"

    id = db.Column(db.Integer, primary_key=True)
    user_id = db.Column(db.Integer, db.ForeignKey("users.id"), nullable=False, index=True)
    food_id = db.Column(db.Integer, db.ForeignKey("food_items.id"), nullable=True)
    message = db.Column(db.String(255), nullable=False)
    notification_date = db.Column(db.DateTime, default=datetime.utcnow)
    is_read = db.Column(db.Boolean, default=False, nullable=False)

    def __repr__(self):
        return f"<Notification for user {self.user_id}>"


class FoodWaste(db.Model):
    """A waste report: the user threw (part of) an item away.

    Snapshot columns (category / shelf life / days held) are copied from the
    item at report time so the ML training history survives even after the
    food item itself is removed from the inventory.
    """

    __tablename__ = "food_waste"

    id = db.Column(db.Integer, primary_key=True)
    user_id = db.Column(db.Integer, db.ForeignKey("users.id"), nullable=False, index=True)
    food_id = db.Column(db.Integer, db.ForeignKey("food_items.id"), nullable=True)
    food_name_snapshot = db.Column(db.String(120), nullable=False)
    category_snapshot = db.Column(db.String(50), nullable=False)
    wasted_quantity = db.Column(db.Float, nullable=False, default=0.0)
    reason = db.Column(db.String(200), nullable=False, default="Other")
    waste_date = db.Column(db.Date, nullable=False)
    # --- ML snapshot fields ------------------------------------------------
    shelf_life_days = db.Column(db.Integer, nullable=False, default=0)
    days_held = db.Column(db.Integer, nullable=False, default=0)

    def to_ml_record(self):
        """Flat dict consumed by ml/consumption_model.py."""
        return {
            "category": self.category_snapshot,
            "quantity": float(self.wasted_quantity or 0.0),
            "shelf_life_days": int(self.shelf_life_days or 0),
            "days_held": int(self.days_held or 0),
        }

    @property
    def utilisation_ratio(self):
        """Fraction of the printed shelf life the item actually survived."""
        if not self.shelf_life_days:
            return None
        return max(0.0, min(1.5, self.days_held / self.shelf_life_days))

    def __repr__(self):
        return f"<FoodWaste {self.food_name_snapshot} on {self.waste_date}>"


class Recipe(db.Model):
    """A recipe in the shared catalogue used by the recommender."""

    __tablename__ = "recipes"

    id = db.Column(db.Integer, primary_key=True)
    recipe_name = db.Column(db.String(150), nullable=False)
    ingredients = db.Column(db.Text, nullable=False)  # comma separated list
    instructions = db.Column(db.Text, nullable=False)
    category = db.Column(db.String(50), nullable=False, default="Dinner")

    def ingredient_list(self):
        return [i.strip() for i in (self.ingredients or "").split(",") if i.strip()]

    def __repr__(self):
        return f"<Recipe {self.recipe_name}>"
